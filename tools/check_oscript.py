СТРОКА = re.compile(r'^Ошибка в строке: (\d+),(\d+) / (.*)$')
НЕИЗВЕСТНЫЕ = re.compile(r'^unknown symbols: (\d+) \((.*)\)$')
ДИРЕКТИВА = re.compile(r'^[ \t]*#(Если|ИначеЕсли|Иначе|КонецЕсли|Область|КонецОбласти|If|ElsIf|Else|EndIf|Region|'
                       r'EndRegion)\b.*$', re.M | re.I)
УСЛОВИЕ = re.compile(r'^[ \t]*#(Если|If)\b', re.M | re.I)  # код прячет только условие, #Область - нет
ПОВТОР = re.compile(r'^(Метод|Method) (\S+) (уже определен|already defined)', re.I)


def движок():
    путь = os.environ.get('VANTEAM_OSCRIPT') or os.path.join(
        os.environ.get('LOCALAPPDATA', ''), 'Programs', 'OneScript-' + ВЕРСИЯ, 'bin', 'oscript.exe')
    return путь if os.path.isfile(путь) else None


def собрать(пути):
    файлы = []
    for п in пути:
        п = os.path.abspath(п)
        if os.path.isfile(п):
            файлы.append(п)
            continue
        for корень, папки, имена in os.walk(п):
            папки[:] = sorted(x for x in папки if x not in ПРОПУСК)
            файлы += [os.path.join(корень, и) for и in sorted(имена) if и.lower().endswith(('.bsl', '.os'))]
    return list(dict.fromkeys(файлы))


def прочитать(ф):
    try:
        # переводы строк как в файле: на LF и CRLF OneScript ставит позицию ошибки выражения по-разному
        with open(ф, encoding='utf-8-sig', newline='') as f:
            return f.read()
    except (UnicodeDecodeError, OSError):
        return None


def общие_модули(файлы):
    """Имена общих модулей проекта по каталогам выгрузки: CommonModule(s)/<Имя>/..., ОбщиеМодули/<Имя>/..."""
    имена = set()
    for ф in файлы:
        части = ф.replace('\\', '/').split('/')
        for i, ч in enumerate(части[:-1]):
            if ч in ('CommonModule', 'CommonModules', 'ОбщиеМодули') and i + 1 < len(части) - 1:
                имена.add(части[i + 1])
    return имена


def строка_метода(текст, имя, после=0):
    """Номер строки второго объявления метода: -checkall сообщает повтор без позиции."""
    шаблон = re.compile(r'^[ \t]*(Процедура|Функция|Procedure|Function)[ \t]+' + re.escape(имя) + r'[ \t]*\(', re.M | re.I)
    строки = [текст.count('\n', 0, m.start()) + 1 for m in шаблон.finditer(текст)]
    return строки[1] if len(строки) > 1 else после


def запустить(exe, пути):
    """Один запуск -checkall на пачку файлов; пачки режутся по длине командной строки Windows."""
    вывод, пачка, длина = [], [], 0
    for п in пути + [None]:
        if п is not None and длина + len(п) < 24000:
            пачка.append(п)
            длина += len(п) + 3
            continue
        if пачка:
            рез = subprocess.run([exe, '-encoding=utf-8', '-checkall'] + пачка, capture_output=True,
                                 timeout=120 + 5 * len(пачка))
            текст = (рез.stdout + рез.stderr).decode('utf-8', 'replace')
            if 'Files: ' not in текст:
                raise RuntimeError('движок не выполнил -checkall (нужен OneScript %s): %s' % (ВЕРСИЯ, текст.strip()[:300]))
            вывод += текст.splitlines()
        if п is not None:
            пачка, длина = [п], len(п) + 3
    return вывод


def разобрать(строки, пути):
    """{путь: {'errors': [(стр, кол, текст)], 'unknown': (число, [имена], ещё), 'failed': текст}}"""
    итог = {п: {'errors': [], 'unknown': (0, [], 0), 'failed': None} for п in пути}
    for s in строки:
        путь, _, остаток = s.partition(': ')
        if путь not in итог:
            continue
        m = СТРОКА.match(остаток)
        if m:
            итог[путь]['errors'].append((int(m.group(1)), int(m.group(2)), m.group(3).strip()))
            continue
        m = НЕИЗВЕСТНЫЕ.match(остаток)
        if m:
            части = [x.strip() for x in m.group(2).split(';')]
            ещё = int(части.pop()[5:]) if части and части[-1].startswith('... +') else 0
            имена = [x.split(':', 1)[-1].strip() for x in части]
            итог[путь]['unknown'] = (int(m.group(1)), имена, ещё)
            continue
        if остаток.startswith('not checked: '):
            итог[путь]['failed'] = остаток[len('not checked: '):]
    return итог


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    тихо = '--quiet' in argv
    все_символы = '--symbols' in argv
    пути = [a for a in argv if not a.startswith('--')]
    try:
        sys.stdout.reconfigure(errors='replace')
    except AttributeError:
        pass
    exe = движок()
    if not exe:
        print('Проверка не выполнена: нет OneScript %s. Установить из релиза в %%LOCALAPPDATA%%\\Programs\\OneScript-%s '
              'или задать VANTEAM_OSCRIPT.' % (ВЕРСИЯ, ВЕРСИЯ), file=sys.stderr)
        return 3
    if not пути:
        пути = [к for к in КОРНИ if os.path.isdir(к)]
    файлы = собрать(пути)
    if not файлы:
        print('Файлов .bsl/.os нет: %s' % ', '.join(пути or КОРНИ))
        return 0
    свои_модули = общие_модули(файлы)
    начало = time.perf_counter()
    with tempfile.TemporaryDirectory(prefix='check_oscript_') as врем:
        копии, тексты = {}, {}
        for i, ф in enumerate(файлы):
            текст = прочитать(ф)
            тексты[ф] = текст
            if текст and УСЛОВИЕ.search(текст):
                копия = os.path.join(врем, '%04d_%s' % (i, os.path.basename(ф)))
                with open(копия, 'w', encoding='utf-8-sig', newline='') as f:
                    f.write(ДИРЕКТИВА.sub('', текст))
                копии[ф] = копия
        try:
            итог = разобрать(запустить(exe, файлы + list(копии.values())), файлы + list(копии.values()))
        except (RuntimeError, subprocess.TimeoutExpired, OSError) as e:
            print('Проверка не выполнена: %s' % e, file=sys.stderr)
            return 2
    время = time.perf_counter() - начало

    база = os.getcwd()
    с_ошибками = не_проверено = 0
    неизвестных, ручные = 0, {}
    for ф in файлы:
        коротко = os.path.relpath(ф, база) if ф.startswith(база) else ф
        р = итог[ф]
        ошибки = []
        for стр, кол, текст in р['errors']:
            m = ПОВТОР.match(текст)
            if m and стр == 0 and тексты[ф]:
                стр = строка_метода(тексты[ф], m.group(2))
            ошибки.append((стр, кол, текст, ''))
        if ф in копии:
            к = итог[копии[ф]]
            свои = {(e[0], e[2]) for e in р['errors']}
            for стр, кол, текст in к['errors']:
                if ПОВТОР.match(текст) or (стр, текст) in свои:
                    continue
                ошибки.append((стр, кол, текст, 'ветка #Если'))
            if р['failed'] is None and к['failed'] is not None and not р['errors']:
                ошибки.append((0, 0, 'копия без директив не проверена: ' + к['failed'], 'ветка #Если'))
            if к['unknown'][0] > р['unknown'][0]:
                р['unknown'] = к['unknown']
        if р['failed'] is not None:
            не_проверено += 1
            print('  НЕ ПРОВЕРЕН %s: %s' % (коротко, р['failed']))
            continue
        число, имена, ещё = р['unknown']
        неизвестных += число
        for имя in имена:
            if имя not in КОНТЕКСТ_1С and имя not in свои_модули:
                ручные.setdefault(имя, коротко)
        if ошибки:
            с_ошибками += 1
            for стр, кол, текст, пометка in sorted(set(ошибки)):
                print('  ОШИБКА   %s  стр %s,%s  %s%s' % (коротко, стр, кол, текст, '  [%s]' % пометка if пометка else ''))
        elif not тихо:
            print('  OK       %s' % коротко)
        if все_символы and число:
            print('           неизвестные символы: %d (%s%s)' % (число, '; '.join(имена), '; ... +%d' % ещё if ещё else ''))
    print()
    if неизвестных:
        print('Неизвестные символы: %d - не ошибка, standalone OneScript не знает контекста 1С.' % неизвестных)
    if ручные:
        # реквизиты объекта и формы сюда тоже попадают: список для глаз, не для кода возврата
        print('Проверить вручную, нет ли опечатки (%d имён вне списка контекста 1С и общих модулей проекта; по файлам - '
              '--symbols): %s%s' % (len(ручные), ', '.join(sorted(ручные)[:20]),
                                   ' ... +%d' % (len(ручные) - 20) if len(ручные) > 20 else ''))
    print('OneScript %s -checkall: файлов %d, с ошибками %d, не проверено %d, модулей с #Если %d, %.1f с' % (
        ВЕРСИЯ, len(файлы), с_ошибками, не_проверено, len(копии), время))
    return 2 if не_проверено else 1 if с_ошибками else 0


if __name__ == '__main__':
    sys.exit(main())
