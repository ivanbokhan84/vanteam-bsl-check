# -*- coding: utf-8 -*-
"""Уровень 1 проверки BSL: модули 1С движком OneScript 2.2.0-vanteam.2 в режиме -checkall.

Уровень 2 - BSL Language Server - отдельной командой: python tools/check_bsl.py <модуль> --deep.

Что проверяется: весь синтаксис модуля и проверки генератора кода (число аргументов своих методов,
процедура как функция, повторное объявление метода, метки). Выводятся все ошибки модуля, не только первая.
Движок запускается один раз на все файлы.

Ветки препроцессора. OneScript не знает символов 1С (Сервер, Клиент, ТолстыйКлиентОбычноеПриложение...),
поэтому код внутри «#Если Сервер Тогда» для него неактивен и не проверяется. Для модулей с директивами
проверяется ещё копия без строк директив (номера строк те же). Ошибки копии, которых нет в исходном файле,
выводятся с пометкой «ветка #Если». Повторное объявление метода в копии не считается: одноимённые методы
разных веток законны.

Неизвестные символы - не ошибка: standalone OneScript не знает метаданных конфигурации, контекста формы и
глобальных функций платформы. Имена вне списка КОНТЕКСТ_1С и не из общих модулей проекта выводятся для
ручной проверки: так видна опечатка в имени переменной. Движок показывает до 10 имён на модуль.

Запуск из корня проекта:
  python tools/check_oscript.py <файл или каталог> [...]
  python tools/check_oscript.py                 все .bsl в каталогах КОРНИ
  --quiet - без строк OK; --symbols - все неизвестные символы по файлам.
Коды возврата: 0 - ошибок нет; 1 - есть ошибки; 2 - файл не удалось проверить; 3 - нет движка.
Движок: переменная окружения VANTEAM_OSCRIPT или
%LOCALAPPDATA%\\Programs\\OneScript-2.2.0-vanteam.2\\bin\\oscript.exe
(сборка из форка https://github.com/ivanbokhan84/OneScript, тег v2.2.0-vanteam.2).
"""
